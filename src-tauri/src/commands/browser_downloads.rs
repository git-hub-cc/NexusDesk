    // Local HTTP fixture exercises actual Range requests, concurrent writes,
    // cookie forwarding and rejection of servers that return invalid ranges.
    async fn fixture(mode: &'static str) -> (String, tokio::task::JoinHandle<()>) {
        use tokio::io::{AsyncReadExt, AsyncWriteExt};
        let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
        let address = listener.local_addr().unwrap();
        let barrier = Arc::new(tokio::sync::Barrier::new(4));
        let task = tokio::spawn(async move {
            loop {
                let (mut socket, _) = listener.accept().await.unwrap();
                let barrier = barrier.clone();
                tokio::spawn(async move {
                    let mut request = Vec::new();
                    while !request.ends_with(b"\r\n\r\n") {
                        let mut byte = [0];
                        if socket.read_exact(&mut byte).await.is_err() {
                            return;
                        }
                        request.push(byte[0]);
                    }
                    let request = String::from_utf8(request).unwrap().to_ascii_lowercase();
                    assert!(request.contains("cookie: session=test"));
                    let range = request
                        .lines()
                        .find_map(|l| l.strip_prefix("range: bytes="))
                        .unwrap();
                    let (start, end) = range.split_once('-').unwrap();
                    let start: usize = start.parse().unwrap();
                    let end: usize = end.parse().unwrap();
                    let probe = start == 0 && end == 0;
                    if mode == "valid" && !probe {
                        barrier.wait().await;
                    }
                    let status = if mode == "ignore" {
                        "200 OK"
                    } else {
                        "206 Partial Content"
                    };
                    let etag = if mode == "changed" && !probe {
                        "other"
                    } else {
                        "fixture"
                    };
                    let actual_start = if mode == "wrong" && !probe {
                        start + 1
                    } else {
                        start
                    };
                    let length = end - start + 1;
                    let validator = match mode {
                        "missing" => String::new(),
                        "weak" => "ETag: W/\"fixture\"\r\n".into(),
                        _ => format!("ETag: \"{etag}\"\r\n"),
                    };
                    let header = format!(
                        "HTTP/1.1 {status}\r\nContent-Length: {length}\r\nContent-Range: bytes {actual_start}-{end}/8193\r\n{validator}Connection: close\r\n\r\n"
                    );
                    if socket.write_all(header.as_bytes()).await.is_err() {
                        return;
                    }
                    let mut body: Vec<_> = (start..=end).map(|n| (n % 251) as u8).collect();
                    if mode == "truncated" && !probe {
                        body.pop();
                    }
                    let _ = socket.write_all(&body).await;
                });
            }
        });
        (format!("http://{address}/download"), task)
    }

